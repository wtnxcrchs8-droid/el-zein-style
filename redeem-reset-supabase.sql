create table if not exists public.loyalty_card_events (
  id bigint generated by default as identity primary key,
  card_id uuid not null references public.loyalty_cards(id) on delete cascade,
  event_type text not null check (event_type in ('reward_redeemed','card_reset')),
  stamps_before integer not null,
  reward_text text,
  performed_by uuid not null,
  created_at timestamptz not null default now()
);

alter table public.loyalty_card_events enable row level security;

create or replace function public.redeem_loyalty_reward(p_card_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_stamps integer;
  v_goal integer;
  v_reward text;
begin
  if auth.uid() is null or not exists (
    select 1 from public.admins where user_id = auth.uid()
  ) then
    raise exception 'Not authorized';
  end if;

  select stamps, stamp_goal, reward
    into v_stamps, v_goal, v_reward
  from public.loyalty_cards
  where id = p_card_id
  for update;

  if not found then raise exception 'Card not found'; end if;
  if v_stamps < v_goal then raise exception 'Not enough stamps'; end if;

  insert into public.loyalty_card_events(card_id,event_type,stamps_before,reward_text,performed_by)
  values (p_card_id,'reward_redeemed',v_stamps,v_reward,auth.uid());

  update public.loyalty_cards set stamps = 0 where id = p_card_id;
end;
$$;

create or replace function public.reset_loyalty_card(p_card_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_stamps integer;
begin
  if auth.uid() is null or not exists (
    select 1 from public.admins where user_id = auth.uid()
  ) then
    raise exception 'Not authorized';
  end if;

  select stamps into v_stamps
  from public.loyalty_cards
  where id = p_card_id
  for update;

  if not found then raise exception 'Card not found'; end if;
  if v_stamps <= 0 then raise exception 'Card is already empty'; end if;

  insert into public.loyalty_card_events(card_id,event_type,stamps_before,performed_by)
  values (p_card_id,'card_reset',v_stamps,auth.uid());

  update public.loyalty_cards set stamps = 0 where id = p_card_id;
end;
$$;

grant execute on function public.redeem_loyalty_reward(uuid) to authenticated;
grant execute on function public.reset_loyalty_card(uuid) to authenticated;
